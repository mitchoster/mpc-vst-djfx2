#!/usr/bin/env python3
"""embed.py — turn the companion page into a C++ string.

The page is edited as HTML (vst/web/index.html, vst/web/404.html) and generated into
src/dsp/companion_page.h, so a page change is an HTML change and the build has no step
that can silently serve an old copy: `embed.py --check` fails the test when the header
and the sources disagree.

    python3 vst/web/embed.py            # write src/dsp/companion_page.h
    python3 vst/web/embed.py --check    # exit 1 when the header is stale
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "src", "dsp", "companion_page.h"))
PARTS = [("kCompanionPage", "index.html"), ("kNotFoundPage", "404.html")]

HEADER = """/* GENERATED by vst/web/embed.py from web/index.html + web/404.html — do not edit here.
 * The source lives in vst/web/; `python3 vst/web/embed.py` regenerates this file and
 * `embed.py --check` (run by vst/tests/companion.sh) fails when it is stale. */
#ifndef DJF2_COMPANION_PAGE_H
#define DJF2_COMPANION_PAGE_H

"""

FOOTER = """
#endif
"""


def build():
    out = [HEADER]
    for name, src in PARTS:
        path = os.path.join(HERE, src)
        text = open(path, encoding="utf-8").read()
        if ")HTML\"" in text:
            sys.exit("error: %s contains the raw-string terminator )HTML\"" % src)
        out.append('/* %s */\nstatic const char %s[] = R"HTML(%s)HTML";\n\n' % (src, name, text))
    out.append(FOOTER)
    return "".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        try:
            current = open(OUT, encoding="utf-8").read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print("FAIL: %s is stale — run vst/web/embed.py" % os.path.relpath(OUT))
            return 1
        print("PASS: the embedded page matches vst/web/")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(OUT), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
